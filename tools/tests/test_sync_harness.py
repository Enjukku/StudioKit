class Base(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="sync_harness_"))
        shutil.copy(KIT_ROOT / "kit.json", self.tmp / "kit.json")
        self.kit = json.loads((self.tmp / "kit.json").read_text(encoding="utf-8"))
        (self.tmp / ".agents" / "roles").mkdir(parents=True)
        (self.tmp / ".agents" / "skills").mkdir(parents=True)

    def tearDown(self) -> None:
        shutil.rmtree(self.tmp, ignore_errors=True)

    def write(self, rel: str, text: str | bytes) -> Path:
        p = self.tmp / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(text, bytes):
            p.write_bytes(text)
        else:
            p.write_bytes(text.encode("utf-8"))
        return p

    def sync(self, check: bool = False) -> tuple[int, str]:
        buf = io.StringIO()
        code = sh.run(self.tmp, check, out=buf)
        return code, buf.getvalue()


class FrontmatterTests(unittest.TestCase):
    def test_quoted_description_with_colon_and_quotes(self) -> None:
        fields, body = sh.parse_frontmatter(ROLE_A, "x.md")
        self.assertEqual(fields["description"], 'Reviews maps: says "why" and where; C:\\path ok')
        self.assertEqual(fields["tools"], ["Read", "Grep", "Glob"])
        self.assertEqual(fields["skills"], ["level-design", "art-fundamentals"])
        self.assertTrue(body.startswith("\nYou review levels."))

    def test_plain_description_with_colon_and_block_list(self) -> None:
        text = "---\nname: a\ndescription: Use for: x, y 'z'\nskills:\n  - one\n  - two\ntier: lead\neffort: high\n---\nB\n"
        fields, _ = sh.parse_frontmatter(text, "a.md")
        self.assertEqual(fields["description"], "Use for: x, y 'z'")
        self.assertEqual(fields["skills"], ["one", "two"])

    def test_single_quoted_and_crlf(self) -> None:
        text = "---\r\nname: a\r\ndescription: 'It''s: fine'\r\ntier: lead\r\neffort: low\r\n---\r\nBody\r\n"
        fields, body = sh.parse_frontmatter(text, "a.md")
        self.assertEqual(fields["description"], "It's: fine")
        self.assertEqual(body, "Body\n")

    def test_missing_frontmatter(self) -> None:
        with self.assertRaises(sh.SyncError):
            sh.parse_frontmatter("no frontmatter", "a.md")


class OutputTests(Base):
    def test_claude_output(self) -> None:
        self.write(".agents/roles/level-checker.md", ROLE_A)
        self.write(".agents/roles/copy-bot.md", ROLE_B)
        self.write(".agents/roles/README.md", "# not a role\n")
        code, _ = self.sync()
        self.assertEqual(code, 0)
        text = (self.tmp / ".claude/agents/level-checker.md").read_text(encoding="utf-8")
        self.assertEqual(
            text,
            "---\n"
            "name: level-checker\n"
            'description: "Reviews maps: says \\"why\\" and where; C:\\\\path ok"\n'
            "model: sonnet\n"
            "effort: medium\n"
            "tools: Read, Grep, Glob\n"
            "skills: level-design, art-fundamentals\n"
            "memory: project\n"
            "color: blue\n"
            "---\n"
            "<!-- generated by tools/sync_harness.py from .agents/roles/level-checker.md; edit the source -->\n"
            "\nYou review levels.\nLine two: with colon.\n",
        )
        b = (self.tmp / ".claude/agents/copy-bot.md").read_text(encoding="utf-8")
        self.assertIn("model: haiku\n", b)
        self.assertIn("description: Plain mechanical copier, it copies things\n", b)
        self.assertIn("skills: orchestration, level-design\n", b)
        self.assertNotIn("memory:", b)
        self.assertNotIn("tools:", b)
        self.assertFalse((self.tmp / ".claude/agents/README.md").exists())
        # Generated frontmatter round-trips through our own parser.
        fields, _ = sh.parse_frontmatter(text, "gen")
        self.assertEqual(fields["description"], 'Reviews maps: says "why" and where; C:\\path ok')

    def test_codex_toml_round_trip(self) -> None:
        body = 'Tabs\there, quote " back \\ slash, bell \x07, unicode é ✓\nend\n'
        self.write(
            ".agents/roles/tricky-one.md",
            "---\nname: tricky-one\ndescription: \"Has: colon and \\\"quotes\\\"\"\ntier: lead\neffort: xhigh\n---\n" + body,
        )
        self.assertEqual(self.sync()[0], 0)
        raw = (self.tmp / ".codex/agents/tricky_one.toml").read_bytes()
        self.assertNotIn(b"\r\n", raw)
        self.assertTrue(raw.startswith(b"# generated by tools/sync_harness.py"))
        data = tomllib.loads(raw.decode("utf-8"))
        self.assertEqual(data["name"], "tricky-one")
        self.assertEqual(data["description"], 'Has: colon and "quotes"')
        self.assertEqual(data["model"], self.kit["models"]["codex"]["lead"])
        self.assertEqual(data["model_reasoning_effort"], "xhigh")
        self.assertEqual(data["developer_instructions"], self.kit["codex_preamble"] + "\n\n" + body)
        self.assertIn(b"\\u0007", raw)

    def test_deterministic_and_check(self) -> None:
        self.write(".agents/roles/level-checker.md", ROLE_A)
        self.write(".agents/skills/s1/SKILL.md", "x\n")
        self.assertEqual(self.sync(check=True)[0], 1)  # missing outputs
        self.assertEqual(self.sync()[0], 0)
        self.assertEqual(self.sync(check=True)[0], 0)
        code, out = self.sync()
        self.assertIn("written 0", out)
        # Hand edit of a generated file -> drift.
        p = self.tmp / ".claude/agents/level-checker.md"
        p.write_text(p.read_text(encoding="utf-8") + "extra\n", encoding="utf-8")
        code, out = self.sync(check=True)
        self.assertEqual(code, 1)
        self.assertIn("different: .claude/agents/level-checker.md", out)
        self.assertIn("extra", p.read_text(encoding="utf-8"))  # check wrote nothing
        # Stale output -> drift.
        self.sync()
        (self.tmp / ".agents/roles/level-checker.md").unlink()
        code, out = self.sync(check=True)
        self.assertEqual(code, 1)
        self.assertIn("stale: .claude/agents/level-checker.md", out)
        self.assertIn("stale: .codex/agents/level_checker.toml", out)


class SkillTests(Base):
    def test_skill_mirror_is_byte_copy(self) -> None:
        payload = b"line\r\nbinary \x00\xff\n"
        self.write(".agents/skills/alpha/SKILL.md", "# Alpha\n")
        self.write(".agents/skills/alpha/refs/data.bin", payload)
        self.write(".agents/skills/beta/SKILL.md", "# Beta\n")
        self.assertEqual(self.sync()[0], 0)
        self.assertEqual((self.tmp / ".claude/skills/alpha/refs/data.bin").read_bytes(), payload)
        self.assertEqual((self.tmp / ".claude/skills/beta/SKILL.md").read_text(encoding="utf-8"), "# Beta\n")
        self.assertEqual((self.tmp / ".claude/skills/.generated").read_text(encoding="utf-8"), "alpha\nbeta\n")

    def test_skill_removal_only_for_manifested(self) -> None:
        self.write(".agents/skills/alpha/SKILL.md", "a\n")
        self.write(".agents/skills/beta/SKILL.md", "b\n")
        self.write(".claude/skills/hand-made/SKILL.md", "mine\n")  # never synced
        self.sync()
        shutil.rmtree(self.tmp / ".agents/skills/beta")
        self.write(".claude/skills/alpha/leftover.md", "old\n")  # extra file inside synced skill
        code, out = self.sync()
        self.assertEqual(code, 0)
        self.assertFalse((self.tmp / ".claude/skills/beta").exists())
        self.assertFalse((self.tmp / ".claude/skills/alpha/leftover.md").exists())
        self.assertTrue((self.tmp / ".claude/skills/hand-made/SKILL.md").exists())
        self.assertEqual((self.tmp / ".claude/skills/.generated").read_text(encoding="utf-8"), "alpha\n")
        self.assertEqual(self.sync(check=True)[0], 0)


class StaleTests(Base):
    def test_only_marked_files_removed(self) -> None:
        self.write(".agents/roles/level-checker.md", ROLE_A)
        self.sync()
        self.write(".claude/agents/hand-written.md", "---\nname: hand-written\n---\nmine\n")
        self.write(".codex/agents/hand_written.toml", 'name = "hand_written"\n')
        (self.tmp / ".agents/roles/level-checker.md").unlink()
        code, out = self.sync()
        self.assertEqual(code, 0)
        self.assertFalse((self.tmp / ".claude/agents/level-checker.md").exists())
        self.assertFalse((self.tmp / ".codex/agents/level_checker.toml").exists())
        self.assertTrue((self.tmp / ".claude/agents/hand-written.md").exists())
        self.assertTrue((self.tmp / ".codex/agents/hand_written.toml").exists())
        self.assertIn("removed 2", out)


class ErrorTests(Base):
    def assert_error(self, text: str, fragment: str, fname: str = "bad-role.md") -> None:
        self.write(f".agents/roles/{fname}", text)
        err = io.StringIO()
        old = sys.stderr
        sys.stderr = err
        try:
            code, _ = self.sync()
        finally:
            sys.stderr = old
        self.assertEqual(code, 2)
        self.assertIn(f".agents/roles/{fname}", err.getvalue())
        self.assertIn(fragment, err.getvalue())
        self.assertFalse((self.tmp / ".claude/agents").exists())

    def test_bad_tier(self) -> None:
        self.assert_error("---\nname: bad-role\ndescription: d\ntier: boss\neffort: low\n---\nx\n", "unknown tier 'boss'")

    def test_missing_key(self) -> None:
        self.assert_error("---\nname: bad-role\ndescription: d\ntier: lead\n---\nx\n", "missing required key 'effort'")

    def test_bad_effort(self) -> None:
        self.assert_error("---\nname: bad-role\ndescription: d\ntier: lead\neffort: max\n---\nx\n", "unknown effort")

    def test_name_mismatch(self) -> None:
        self.assert_error("---\nname: other\ndescription: d\ntier: lead\neffort: low\n---\nx\n", "does not match")

    def test_unknown_key(self) -> None:
        self.assert_error("---\nname: bad-role\ndescription: d\ntier: lead\neffort: low\nmodel: opus\n---\nx\n", "unknown key")


