        self.assertFalse((self.tmp / ".claude/workflows/effect.js").exists())
        self.assertEqual(out_file.read_bytes(), JOB_JS)
        self.assertEqual((self.tmp / ".claude/workflows/.generated").read_text(encoding="utf-8"), "cutscene.js\n")

