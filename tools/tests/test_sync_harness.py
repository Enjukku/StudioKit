WORKFLOW = """---
description: "Weekly pass: finds mistakes, says \\"why\\""
---

# /demo

Step 1: do it.
"""
MARK = "<!-- generated by tools/sync_harness.py from .agents/workflows/{}.md; edit the source -->"


class WorkflowTests(Base):
    def test_command_is_copy_with_marker(self) -> None:
        self.write(".agents/workflows/demo-flow.md", WORKFLOW)
        self.write(".agents/workflows/README.md", "# not a workflow\n")
        code, _ = self.sync()
        self.assertEqual(code, 0)
        out = (self.tmp / ".claude/commands/demo-flow.md").read_text(encoding="utf-8")
        self.assertEqual(out, WORKFLOW.replace("\n---\n\n", "\n---\n" + MARK.format("demo-flow") + "\n\n", 1))
        self.assertFalse((self.tmp / ".claude/commands/README.md").exists())
        self.assertFalse((self.tmp / ".codex").exists())  # Codex reads .agents/workflows directly
        self.assertEqual(self.sync(check=True)[0], 0)

    def test_crlf_preserved(self) -> None:
        src = WORKFLOW.replace("\n", "\r\n").encode("utf-8")
        self.write(".agents/workflows/crlf.md", src)
        self.sync()
        raw = (self.tmp / ".claude/commands/crlf.md").read_bytes()
        line = (MARK.format("crlf") + "\r\n").encode("utf-8")
        self.assertIn(b"---\r\n" + line, raw)
        self.assertEqual(raw.replace(line, b""), src)

    def test_drift_and_stale(self) -> None:
        self.write(".agents/workflows/demo-flow.md", WORKFLOW)
        self.write(".claude/commands/hand-made.md", "---\ndescription: mine\n---\nmine\n")
        self.assertEqual(self.sync(check=True)[0], 1)
        self.sync()
        p = self.tmp / ".claude/commands/demo-flow.md"
        p.write_text(p.read_text(encoding="utf-8") + "edit\n", encoding="utf-8")
        code, out = self.sync(check=True)
        self.assertEqual(code, 1)
        self.assertIn("different: .claude/commands/demo-flow.md", out)
        (self.tmp / ".agents/workflows/demo-flow.md").unlink()
        code, out = self.sync(check=True)
        self.assertIn("stale: .claude/commands/demo-flow.md", out)
        self.assertNotIn("hand-made", out)
        code, _ = self.sync()
        self.assertEqual(code, 0)
        self.assertFalse(p.exists())
        self.assertTrue((self.tmp / ".claude/commands/hand-made.md").exists())

    def _error(self, rel: str, text: str, fragment: str) -> None:
        self.write(rel, text)
        err = io.StringIO()
        old, sys.stderr = sys.stderr, err
        try:
            code, _ = self.sync()
        finally:
            sys.stderr = old
        self.assertEqual(code, 2)
        self.assertIn(rel, err.getvalue())
        self.assertIn(fragment, err.getvalue())

    def test_missing_description(self) -> None:
        self._error(".agents/workflows/no-desc.md", "---\nname: x\n---\nbody\n", "missing required key 'description'")

    def test_missing_frontmatter(self) -> None:
        self._error(".agents/workflows/plain.md", "# no frontmatter\n", "missing frontmatter")

    def test_bad_name(self) -> None:
        self._error(".agents/workflows/Bad_Name.md", WORKFLOW, "not kebab-case")


