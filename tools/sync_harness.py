# CLI
# --------------------------------------------------------------------------


def _prune_empty_dirs(start: Path, stop: Path) -> None:
    cur = start
    while cur != stop and cur.is_dir() and not any(cur.iterdir()):
        cur.rmdir()
        cur = cur.parent


def run(root: Path, check: bool, out=sys.stdout) -> int:
    try:
        desired, stale = build_plan(root)
    except SyncError as exc:
        print(f"sync_harness: error: {exc}", file=sys.stderr)
        return 2

    missing, different, unchanged = [], [], []
    for rel in sorted(desired):
        path = root / rel
        if not path.is_file():
            missing.append(rel)
        elif path.read_bytes() != desired[rel]:
            different.append(rel)
        else:
            unchanged.append(rel)

    if check:
        if not (missing or different or stale):
            print(f"sync_harness: in sync ({len(unchanged)} files)", file=out)
            return 0
        print("sync_harness: DRIFT (run python tools/sync_harness.py)", file=out)
        for label, items in (("missing", missing), ("different", different), ("stale", stale)):
            for rel in items:
                print(f"  {label}: {rel}", file=out)
        return 1

    for rel in missing + different:
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(desired[rel])
    for rel in stale:
        path = root / rel.rstrip("/")
        if rel.endswith("/"):
            shutil.rmtree(path)
        else:
            path.unlink()
        _prune_empty_dirs(path.parent, root)
    print(
        f"sync_harness: written {len(missing) + len(different)}, "
        f"unchanged {len(unchanged)}, removed {len(stale)}",
        file=out,
    )
    for rel in missing + different:
        print(f"  written: {rel}", file=out)
    for rel in stale:
        print(f"  removed: {rel}", file=out)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 on drift")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args(argv)
    return run(args.root.resolve(), args.check)


if __name__ == "__main__":
    sys.exit(main())
