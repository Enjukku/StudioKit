def load_kit(root: Path) -> dict:
    path = root / "kit.json"
    if not path.is_file():
        raise SyncError("kit.json: file not found")
    try:
        kit = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SyncError(f"kit.json: invalid JSON ({exc})") from exc
    for harness in ("claude", "codex"):
        models = kit.get("models", {}).get(harness)
        if not isinstance(models, dict):
            raise SyncError(f"kit.json: missing models.{harness}")
        for tier in TIERS:
            if not isinstance(models.get(tier), str) or not models[tier]:
                raise SyncError(f"kit.json: missing models.{harness}.{tier}")
    if not isinstance(kit.get("codex_preamble"), str):
        raise SyncError("kit.json: missing codex_preamble")
    return kit


def _has_marker(path: Path, prefix: str, first_line_only: bool) -> bool:
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    if first_line_only:
        return text.split("\n", 1)[0].startswith(prefix)
    return any(line.startswith(prefix) for line in text.split("\n")[:60])


def _read_manifest(root: Path) -> list[str]:
    path = root / SKILL_MANIFEST
    if not path.is_file():
        return []
    return [ln.strip() for ln in path.read_text(encoding="utf-8").split("\n") if ln.strip()]


def build_plan(root: Path) -> tuple[dict[str, bytes], list[str]]:
    """Return (desired files rel->bytes, stale paths rel to remove; dirs end with '/')."""
    kit = load_kit(root)
    desired: dict[str, bytes] = {}

    roles_dir = root / ".agents" / "roles"
    if roles_dir.is_dir():
        for path in sorted(roles_dir.glob("*.md")):
            if path.name.lower() == "readme.md":
                continue
            rel = path.relative_to(root).as_posix()
            role = load_role(path, rel)
            desired[f".claude/agents/{role.name}.md"] = render_claude(role, kit).encode("utf-8")
            codex_name = role.name.replace("-", "_")
            desired[f".codex/agents/{codex_name}.toml"] = render_codex(role, kit).encode("utf-8")

    workflows_dir = root / ".agents" / "workflows"
    if workflows_dir.is_dir():
        for path in sorted(workflows_dir.glob("*.md")):
            if path.name.lower() == "readme.md":
                continue
            rel = path.relative_to(root).as_posix()
            if not NAME_RE.match(path.stem):
                raise SyncError(f"{rel}: file name '{path.stem}' is not kebab-case")
            text = path.read_bytes().decode("utf-8")
            desired[f".claude/commands/{path.stem}.md"] = render_workflow(text, rel).encode("utf-8")

    skills_src = root / ".agents" / "skills"
    skill_names: list[str] = []
    if skills_src.is_dir():
        for skill_dir in sorted(p for p in skills_src.iterdir() if p.is_dir()):
            skill_names.append(skill_dir.name)
            for f in sorted(p for p in skill_dir.rglob("*") if p.is_file()):
                rel = f.relative_to(skills_src).as_posix()
                desired[f".claude/skills/{rel}"] = f.read_bytes()
    if skill_names or (root / SKILL_MANIFEST).exists():
        desired[SKILL_MANIFEST] = ("".join(n + "\n" for n in skill_names)).encode("utf-8")

    stale: list[str] = []
    for out_dir, pattern, prefix, first in (
        (".claude/agents", "*.md", CLAUDE_MARKER_PREFIX, False),
        (".claude/commands", "*.md", CLAUDE_MARKER_PREFIX, False),
        (".codex/agents", "*.toml", CODEX_MARKER_PREFIX, True),
    ):
        d = root / out_dir
        if d.is_dir():
            for path in sorted(d.glob(pattern)):
                rel = path.relative_to(root).as_posix()
                if rel not in desired and _has_marker(path, prefix, first):
                    stale.append(rel)

    skills_out = root / ".claude" / "skills"
    for name in sorted(set(_read_manifest(root)) - set(skill_names)):
        if name and "/" not in name and "\\" not in name and name not in (".", ".."):
            if (skills_out / name).is_dir():
                stale.append(f".claude/skills/{name}/")
    for name in skill_names:
        out = skills_out / name
        if out.is_dir():
            for f in sorted(p for p in out.rglob("*") if p.is_file()):
                rel = f.relative_to(root).as_posix()
                if rel not in desired:
                    stale.append(rel)
    return desired, stale


