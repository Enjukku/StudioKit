#!/usr/bin/env python3
"""Generate harness files (Claude Code, Codex) from assistant-neutral sources.

Sources:
  .agents/roles/<name>.md      frontmatter + markdown body (README.md ignored)
  .agents/skills/<skill>/**    any files
  .agents/workflows/<name>.md  frontmatter with a `description:` + markdown body (README.md ignored)

Outputs:
  .claude/agents/<name>.md             Claude Code subagent
  .claude/skills/<skill>/**            byte copy of the skill
  .claude/skills/.generated            manifest of synced skill names
  .claude/commands/<name>.md           Claude Code slash command: exact copy of the workflow with the
                                       generated marker line inserted after the frontmatter
  .codex/agents/<name_with_underscores>.toml   Codex agent
  (Codex gets no workflow output: it reads .agents/workflows/ directly.)

Stale removal: a generated agent, command or Codex file (it carries the marker) whose source is gone
is removed; a skill folder is removed only if the manifest lists it. Hand-written files are never touched.
--check writes nothing and reports missing, different and stale files.

Usage:
  python tools/sync_harness.py [--check] [--root DIR]

Exit codes: 0 ok / in sync, 1 drift (--check), 2 bad source or config.
Python 3 standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path

SCRIPT = "tools/sync_harness.py"
CLAUDE_MARKER_PREFIX = "<!-- generated by tools/sync_harness.py"
CODEX_MARKER_PREFIX = "# generated by tools/sync_harness.py"
SKILL_MANIFEST = ".claude/skills/.generated"

TIERS = ("lead", "craft", "research", "mechanical")
EFFORTS = ("low", "medium", "high", "xhigh")
MEMORIES = ("project", "user", "local", "none")
REQUIRED_KEYS = ("name", "description", "tier", "effort")
OPTIONAL_KEYS = ("tools", "skills", "memory", "color")
LIST_KEYS = ("tools", "skills")
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


class SyncError(Exception):
    """A source or config problem. Message names the file and the reason."""


# --------------------------------------------------------------------------
# Frontmatter parsing (small YAML subset)
# --------------------------------------------------------------------------


def _unquote(raw: str, where: str) -> str:
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] == '"':
        inner = raw[1:-1]
        out = []
        i = 0
        escapes = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "/": "/", "0": "\0"}
        while i < len(inner):
            ch = inner[i]
            if ch == "\\":
                if i + 1 >= len(inner):
                    raise SyncError(f"{where}: dangling backslash in quoted string")
                nxt = inner[i + 1]
                if nxt in escapes:
                    out.append(escapes[nxt])
                    i += 2
                    continue
                if nxt == "u" and i + 6 <= len(inner):
                    out.append(chr(int(inner[i + 2 : i + 6], 16)))
                    i += 6
                    continue
                raise SyncError(f"{where}: unsupported escape \\{nxt}")
            out.append(ch)
            i += 1
        return "".join(out)
    if len(raw) >= 2 and raw[0] == raw[-1] == "'":
        return raw[1:-1].replace("''", "'")
    return raw


def _split_list(raw: str, where: str) -> list[str]:
    raw = raw.strip()
    if raw.startswith("["):
        if not raw.endswith("]"):
            raise SyncError(f"{where}: unclosed [ list")
        raw = raw[1:-1]
    items = [_unquote(p, where) for p in raw.split(",")]
    return [i.strip() for i in items if i.strip()]


def parse_frontmatter(text: str, where: str) -> tuple[dict, str]:
    """Return (fields, body). Lists are returned as list[str]."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if text.startswith("﻿"):
        text = text[1:]
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise SyncError(f"{where}: missing frontmatter (first line must be ---)")
    end = None
    for idx in range(1, len(lines)):
        if lines[idx].strip() == "---":
            end = idx
            break
    if end is None:
        raise SyncError(f"{where}: frontmatter not closed with ---")

    fields: dict = {}
    current_list_key = None
    for lineno, line in enumerate(lines[1:end], start=2):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("- ") or stripped == "-":
            if current_list_key is None:
                raise SyncError(f"{where}:{lineno}: list item without a key")
            item = _unquote(stripped[1:].strip(), f"{where}:{lineno}")
            if item:
                fields[current_list_key].append(item)
            continue
        if line[:1].isspace():
            raise SyncError(f"{where}:{lineno}: unexpected indented line")
        if ":" not in line:
            raise SyncError(f"{where}:{lineno}: expected 'key: value'")
        key, value = line.split(":", 1)
        key = key.strip()
        value = value.strip()
        if key in fields:
            raise SyncError(f"{where}:{lineno}: duplicate key '{key}'")
        current_list_key = None
        if key in LIST_KEYS:
            if value == "":
                fields[key] = []
                current_list_key = key
            else:
                fields[key] = _split_list(value, f"{where}:{lineno}")
        else:
            fields[key] = _unquote(value, f"{where}:{lineno}")
    body = "\n".join(lines[end + 1 :])
    return fields, body


def render_workflow(text: str, rel: str) -> str:
    """Exact copy of the workflow with the marker line inserted after the closing frontmatter line."""
    fields, _ = parse_frontmatter(text, rel)  # raises on missing or unclosed frontmatter
    if not fields.get("description"):
        raise SyncError(f"{rel}: missing required key 'description'")
    lines = text.splitlines(keepends=True)
    end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    eol = "\r\n" if lines[end].endswith("\r\n") or lines[0].endswith("\r\n") else "\n"
    if not lines[end].endswith(("\n", "\r")):
        lines[end] += eol
    marker = f"{CLAUDE_MARKER_PREFIX} from {rel}; edit the source -->{eol}"
    return "".join(lines[: end + 1]) + marker + "".join(lines[end + 1 :])


@dataclass
class Role:
    name: str
    description: str
    tier: str
    effort: str
    body: str
    source: str
    tools: list[str] = field(default_factory=list)
    skills: list[str] = field(default_factory=list)
    memory: str = "project"
    color: str = ""


def load_role(path: Path, rel: str) -> Role:
    fields, body = parse_frontmatter(path.read_text(encoding="utf-8"), rel)
    for key in REQUIRED_KEYS:
        if not fields.get(key):
            raise SyncError(f"{rel}: missing required key '{key}'")
    unknown = sorted(set(fields) - set(REQUIRED_KEYS) - set(OPTIONAL_KEYS))
    if unknown:
        raise SyncError(f"{rel}: unknown key(s) {', '.join(unknown)}")
    name = fields["name"]
    if not NAME_RE.match(name):
        raise SyncError(f"{rel}: name '{name}' is not kebab-case")
    if name != path.stem:
        raise SyncError(f"{rel}: name '{name}' does not match file name '{path.stem}'")
    if fields["tier"] not in TIERS:
        raise SyncError(f"{rel}: unknown tier '{fields['tier']}' (expected {' | '.join(TIERS)})")
    if fields["effort"] not in EFFORTS:
        raise SyncError(f"{rel}: unknown effort '{fields['effort']}' (expected {' | '.join(EFFORTS)})")
    memory = fields.get("memory") or "project"
    if memory not in MEMORIES:
        raise SyncError(f"{rel}: unknown memory '{memory}' (expected {' | '.join(MEMORIES)})")
    return Role(
        name=name,
        description=fields["description"],
        tier=fields["tier"],
        effort=fields["effort"],
        body=body,
        source=rel,
        tools=list(fields.get("tools") or []),
        skills=list(fields.get("skills") or []),
        memory=memory,
        color=fields.get("color") or "",
    )


