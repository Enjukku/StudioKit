# Rendering
# --------------------------------------------------------------------------

_PLAIN_RE = re.compile(r"^[A-Za-z0-9_(][^\n]*$")


def yaml_scalar(value: str) -> str:
    """Plain scalar when safe, otherwise a double-quoted YAML string."""
    unsafe = (
        not _PLAIN_RE.match(value)
        or value != value.strip()
        or ": " in value
        or " #" in value
        or value.endswith(":")
        or value.lower() in ("true", "false", "yes", "no", "null", "on", "off", "~")
    )
    if not unsafe:
        return value
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\u{ord(ch):04X}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def toml_string(value: str) -> str:
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\u{ord(ch):04X}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _ensure_trailing_newline(text: str) -> str:
    return text if text.endswith("\n") else text + "\n"


def render_claude(role: Role, kit: dict) -> str:
    lines = [
        "---",
        f"name: {role.name}",
        f"description: {yaml_scalar(role.description)}",
        f"model: {kit['models']['claude'][role.tier]}",
        f"effort: {role.effort}",
    ]
    if role.tools:
        lines.append(f"tools: {', '.join(role.tools)}")
    if role.skills:
        lines.append(f"skills: {', '.join(role.skills)}")
    if role.memory != "none":
        lines.append(f"memory: {role.memory}")
    if role.color:
        lines.append(f"color: {yaml_scalar(role.color)}")
    lines.append("---")
    lines.append(f"{CLAUDE_MARKER_PREFIX} from {role.source}; edit the source -->")
    return _ensure_trailing_newline("\n".join(lines) + "\n" + role.body)


def render_codex(role: Role, kit: dict) -> str:
    instructions = kit["codex_preamble"] + "\n\n" + _ensure_trailing_newline(role.body.lstrip("\n"))
    lines = [
        f"{CODEX_MARKER_PREFIX} from {role.source}; edit the source",
        f"name = {toml_string(role.name)}",
        f"description = {toml_string(role.description)}",
        f"model = {toml_string(kit['models']['codex'][role.tier])}",
        f"model_reasoning_effort = {toml_string(role.effort)}",
        f"developer_instructions = {toml_string(instructions)}",
    ]
    return "\n".join(lines) + "\n"


