#!/usr/bin/env python3
"""Knowledge-base area indexes and lint.

Kit tool (universal). Standard library only, deterministic output.

Usage:
    python tools/kb_index.py            # write knowledge/generated/index-<area>.md, print lint counts
    python tools/kb_index.py --lint     # full lint report, no writes; exit 1 on errors
    python tools/kb_index.py --check    # no writes; exit 1 if generated indexes are stale
    (flags combine: `--lint --check` is the gate form)

Areas = top-level folders of knowledge/ (design, systems, lessons, jobs, reference, logs,
overlays, ...), minus generated/ and external/; knowledge/inbox/processed/ is skipped.
Never touches knowledge/index.md (hand-written; it links to the generated indexes).

Lint (rules/knowledge.md §3):
    ERROR  missing frontmatter, unparseable frontmatter, missing/invalid type, scope, status,
           updated (relative dates such as "today" or "last week" included), dead [[links]],
           superseded note with no replacement link
    WARN   missing source, unknown keys, supersedes path not found, no author line,
           note over 300 lines, duplicate titles
    README.md files and anything under a templates/ folder are exempt from frontmatter.
    Dead-link check also covers rules/, .agents/ and AGENTS.md (the packet corpus).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import context_packet as cp  # noqa: E402

GENERATED = "knowledge/generated"
INDEX_PREFIX = "index-"
SKIP_AREAS = {"generated", "external"}
SKIP_PATHS = ("knowledge/inbox/processed",)
MAX_LINES = 300

TYPES = {"decision", "lesson", "failed", "system", "job", "reference", "log", "index", "profile", "overlay"}
SCOPES = {"universal", "game"}
STATUSES = {"draft", "active", "superseded"}
REQUIRED = ("type", "scope", "status", "updated")
KNOWN_KEYS = {"type", "scope", "status", "updated", "source", "supersedes", "superseded_by", "description", "name"}
RELATIVE_DATE_RE = re.compile(
    r"\b(today|yesterday|tomorrow|now|recently|last|next|this|ago|week|month|year|days?)\b", re.IGNORECASE
)


# ---------------------------------------------------------------- collection


def knowledge_notes(root: Path) -> list[str]:
    base = root / "knowledge"
    if not base.is_dir():
        return []
    found = []
    for path in base.rglob("*.md"):
        rel = path.relative_to(root).as_posix()
        parts = rel.split("/")
        if not path.is_file() or cp.SKIP_DIRS.intersection(parts):
            continue
        if len(parts) > 2 and parts[1] in SKIP_AREAS:
            continue
        if any(rel.startswith(skip + "/") for skip in SKIP_PATHS):
            continue
        found.append(rel)
    return sorted(found, key=str.lower)


def exempt(rel: str) -> bool:
    return Path(rel).name.lower() == "readme.md" or "templates" in rel.split("/")


def summary_of(note: cp.Note) -> str:
    in_fence = False
    for line in note.lines[note.body_start :]:
        text = line.strip()
        if cp.FENCE_RE.match(text):
            in_fence = not in_fence
            continue
        if in_fence or not text or text.startswith(("#", ">", "|", "---", "<!--")):
            continue
        text = re.sub(r"^[-*+]\s+|^\d+\.\s+", "", text)
        sentence = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
        return cp.clip(sentence, 140)
    return ""


# ---------------------------------------------------------------- indexes


def cell(value) -> str:
    if isinstance(value, list):
        value = ", ".join(str(v) for v in value)
    text = str(value or "-").replace("|", "\\|")
    return text if text.strip() else "-"


def build_indexes(root: Path) -> dict[str, str]:
    """Return {repo-relative output path: content} for every non-empty area."""
    by_area: dict[str, list[cp.Note]] = {}
    for rel in knowledge_notes(root):
        parts = rel.split("/")
        if len(parts) < 3:
            continue  # knowledge/index.md and other root files belong to no area
        by_area.setdefault(parts[1], []).append(cp.load_note(root, root / rel))
    outputs: dict[str, str] = {}
    for area in sorted(by_area):
        notes = sorted(by_area[area], key=lambda n: n.path.lower())
        lines = [
            f"# Index: {area}",
            "",
            f"> Generated by `tools/kb_index.py` from `knowledge/{area}/`; do not edit. {len(notes)} notes.",
            "",
            "| note | type | scope | status | updated | summary |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for note in notes:
            meta = note.meta or {}
            link = f"[{cell(note.title)}](../{note.path.split('/', 1)[1]})"
            lines.append(
                f"| {link} | {cell(meta.get('type'))} | {cell(meta.get('scope'))} | {cell(meta.get('status'))} "
                f"| {cell(meta.get('updated'))} | {cell(summary_of(note))} |"
            )
        outputs[f"{GENERATED}/{INDEX_PREFIX}{area}.md"] = "\n".join(lines) + "\n"
    return outputs


def existing_indexes(root: Path) -> dict[str, str]:
    base = root / GENERATED
    if not base.is_dir():
        return {}
    return {
        path.relative_to(root).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted(base.glob(f"{INDEX_PREFIX}*.md"))
    }


def stale(root: Path) -> list[str]:
    want = build_indexes(root)
    have = existing_indexes(root)
    problems = [f"missing {p}" for p in sorted(set(want) - set(have))]
    problems += [f"stale {p}" for p in sorted(set(want) & set(have)) if want[p] != have[p].replace("\r\n", "\n")]
    problems += [f"orphan {p} (area has no notes)" for p in sorted(set(have) - set(want))]
    return problems


def write_indexes(root: Path) -> list[str]:
    want = build_indexes(root)
    changed = []
    for rel, content in want.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        old = path.read_text(encoding="utf-8") if path.is_file() else None
        if old != content:
            path.write_text(content, encoding="utf-8", newline="\n")
            changed.append(rel)
    for rel in sorted(set(existing_indexes(root)) - set(want)):
        (root / rel).unlink()
        changed.append(f"removed {rel}")
    return changed


# ---------------------------------------------------------------- lint


def lint(root: Path) -> tuple[list[str], list[str]]:
    corpus = cp.Corpus(root)
    errors: list[str] = []
    warnings: list[str] = []
    titles: dict[str, list[str]] = {}

    for rel in knowledge_notes(root):
        note = corpus.notes.get(rel) or cp.load_note(root, root / rel)
        titles.setdefault(note.title.strip().lower(), []).append(rel)
        if len(note.lines) > MAX_LINES:
            warnings.append(f"{rel}: {len(note.lines)} lines (over {MAX_LINES}; split it)")
        for problem in note.fm_errors:
            errors.append(f"{rel}: frontmatter {problem}")
        if exempt(rel):
            continue
        meta = note.meta
        if meta is None:
            if not note.fm_errors:
                errors.append(f"{rel}:1: missing frontmatter (type, scope, status, updated, source)")
            continue
        for key in REQUIRED:
            if not meta.get(key):
                errors.append(f"{rel}: frontmatter missing `{key}`")
        if meta.get("type") and meta["type"] not in TYPES:
            errors.append(f"{rel}: invalid type `{meta['type']}` (one of {', '.join(sorted(TYPES))})")
        if meta.get("scope") and meta["scope"] not in SCOPES:
            errors.append(f"{rel}: invalid scope `{meta['scope']}` (universal or game)")
        if meta.get("status") and meta["status"] not in STATUSES:
            errors.append(f"{rel}: invalid status `{meta['status']}` (draft, active, superseded)")
        updated = meta.get("updated")
        if updated and cp.parse_date(updated) is None:
            kind = "relative date" if isinstance(updated, str) and RELATIVE_DATE_RE.search(updated) else "invalid date"
            errors.append(f"{rel}: `updated: {updated}` is a {kind}; use YYYY-MM-DD")
        if not meta.get("source"):
            warnings.append(f"{rel}: frontmatter missing `source`")
        for key in sorted(set(meta) - KNOWN_KEYS):
            warnings.append(f"{rel}: unknown frontmatter key `{key}`")
        sup = meta.get("supersedes") or []
        for target in sup if isinstance(sup, list) else [sup]:
            if target and not (root / str(target)).is_file():
                warnings.append(f"{rel}: supersedes `{target}` which does not exist")
        first = next((l.strip() for l in note.lines[note.body_start :] if l.strip()), "")
        if not first.startswith("> Author:"):
            warnings.append(f"{rel}: no `> Author:` line right after the frontmatter")
        if meta.get("status") == "superseded" and not corpus.replacement_for(note):
            errors.append(f"{rel}: superseded but links no replacement (add [[link]] or superseded_by)")

    checked = sorted(set(corpus.notes) | set(knowledge_notes(root)), key=str.lower)
    for rel in checked:
        note = corpus.notes.get(rel) or cp.load_note(root, root / rel)
        for line, target in note.links:
            if corpus.resolve_link(target, rel) is None:
                errors.append(f"{rel}:{line}: dead link [[{target}]]")

    for title, paths in sorted(titles.items()):
        if title and len(paths) > 1:
            warnings.append(f"duplicate title `{title}`: {', '.join(paths)}")
    return errors, warnings


# ---------------------------------------------------------------- cli


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description="Generate knowledge area indexes and lint notes.")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    ap.add_argument("--lint", action="store_true", help="report lint issues; exit 1 on errors (no writes)")
    ap.add_argument("--check", action="store_true", help="exit 1 if generated indexes are stale (no writes)")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    code = 0
    if not args.lint and not args.check:
        changed = write_indexes(root)
        print(f"kb_index: {len(build_indexes(root))} area indexes, {len(changed)} changed")
        for rel in changed:
            print(f"  {rel}")
        errors, warnings = lint(root)
        print(f"lint: {len(errors)} errors, {len(warnings)} warnings (run --lint for details)")
        return 0
    if args.check:
        problems = stale(root)
        for problem in problems:
            print(f"STALE {problem}")
        print(f"check: {'stale, run python tools/kb_index.py' if problems else 'indexes current'}")
        code = 1 if problems else code
    if args.lint:
        errors, warnings = lint(root)
        for item in errors:
            print(f"ERROR {item}")
        for item in warnings:
            print(f"WARN  {item}")
        print(f"lint: {len(errors)} errors, {len(warnings)} warnings")
        code = 1 if errors else code
    return code


if __name__ == "__main__":
    raise SystemExit(main())
